"""M8 step 1: extra "distractor" tables for the bigger-catalog test.

A real company has hundreds of tables, not 28. To test that, we add tables from public benchmarks
to the CATALOG only (cards, search, map). They are never part of a correct answer.

  Sources: TPC-DS (24 retail tables) and TPC-H (8), generated by DuckDB,
           and BIRD (real databases from a text-to-SQL benchmark, downloaded from Hugging Face).
  Order:   TPC-DS + TPC-H first (retail: sales, promotions, customers - closest to ads), then BIRD in a
           fixed random order (seed 42). Catalog of 100 = our 28 + the first 72; 250 = our 28 + the first 222.
  Cards:   the AI drafts a description per table (one time, saved), same style as our own cards.

Run from the project folder:
    .venv/bin/python catalog/distractors.py
"""
import json
import logging
import random
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import duckdb
import sqlglot
import yaml
from sqlglot import exp

PROJECT = Path(__file__).resolve().parent.parent
sys.path += [str(PROJECT / "catalog"), str(PROJECT / "agent")]
RAW = PROJECT / "data" / "distractors_raw"
CARDS_DIR = PROJECT / "catalog" / "cards"
DISTRACTOR_DIR = PROJECT / "catalog" / "distractor_cards"
ORDER_FILE = DISTRACTOR_DIR / "ORDER.txt"

logging.getLogger("sqlglot").setLevel(logging.ERROR)   # some BIRD schemas have triggers sqlglot skips

SIZES = {28: 0, 100: 72, 250: 222}   # catalog size -> how many distractor tables
SEED = 42
DESCRIBE_MODEL = "gpt-5-mini"


# ---------------------------------------------------------------------
# 1. Read the schemas
# ---------------------------------------------------------------------
def duckdb_benchmark(name, generate):
    """TPC-DS / TPC-H schemas, generated empty by DuckDB."""
    con = duckdb.connect()
    con.execute(f"INSTALL {name}; LOAD {name}; CALL {generate}(sf=0)")
    tables = []
    for (table,) in con.execute("SHOW TABLES").fetchall():
        columns = [{"name": c, "type": t} for c, t, *_ in con.execute(f"DESCRIBE {table}").fetchall()]
        tables.append({"table": f"{name}_{table}", "source": name.upper(), "database": name,
                       "columns": columns, "joins": {}})
    return tables


def clean(name):
    """Table names become letters, numbers and _ only (some BIRD tables have spaces)."""
    return re.sub(r"\W+", "_", name).strip("_")


def parse_create_tables(sql_text, db, source):
    """Tables, columns and foreign keys from CREATE TABLE statements (BIRD schemas)."""
    tables = []
    for statement in sqlglot.parse(sql_text, read="sqlite", error_level=sqlglot.ErrorLevel.IGNORE):
        if not isinstance(statement, exp.Create) or not isinstance(statement.this, exp.Schema):
            continue
        name = statement.this.this.name
        columns, joins = [], {}
        for item in statement.this.expressions:
            if isinstance(item, exp.ColumnDef):
                columns.append({"name": item.name, "type": item.args["kind"].sql() if item.args.get("kind") else "TEXT"})
            elif isinstance(item, exp.ForeignKey):
                ref = item.args.get("reference")
                if ref is not None and item.expressions:
                    target = ref.find(exp.Table)
                    if target is not None:
                        joins[item.expressions[0].name] = clean(f"{db}_{target.name}")
        if columns:
            tables.append({"table": clean(f"{db}_{name}"), "source": source, "database": db, "columns": columns, "joins": joins})
    return tables


def bird_tables():
    tables = []
    minidev = json.loads((RAW / "bird_minidev_sqlite_schemas.json").read_text())
    for db, schema in sorted(minidev.items()):
        tables += parse_create_tables(schema, db, "BIRD")
    train = duckdb.connect().execute(
        f"SELECT db_id, ANY_VALUE(schema) FROM '{RAW / 'bird_train.parquet'}' GROUP BY db_id ORDER BY db_id").fetchall()
    for db, schema in train:
        tables += parse_create_tables(schema, db, "BIRD")
    unique = {}
    for t in tables:
        unique.setdefault(t["table"].lower(), t)
    return list(unique.values())


def distractor_pool():
    """All distractor tables, in the fixed order used for the 100 and 250 catalogs."""
    retail = duckdb_benchmark("tpcds", "dsdgen") + duckdb_benchmark("tpch", "dbgen")
    bird = bird_tables()
    random.Random(SEED).shuffle(bird)
    ours = {p.stem for p in CARDS_DIR.glob("*.yaml")}
    return [t for t in retail + bird if t["table"] not in ours]


# ---------------------------------------------------------------------
# 2. Draft a card for each table (same fields as our own cards)
# ---------------------------------------------------------------------
DESCRIBE_PROMPT = """Write a one-sentence description of this database table for a data catalog: what it holds and
what it is used for, in plain words (like "Final daily impressions, clicks and CTR per campaign."). Then say
what one row means. Reply as JSON: {{"description": "...", "grain": "one row per ..."}}

Database: {database}
Table: {table}
Columns: {columns}"""


def draft_card(t):
    from llm import ask
    columns = ", ".join(f"{c['name']} {c['type']}" for c in t["columns"])
    reply, _ = ask(DESCRIBE_MODEL, "You write short, factual data catalog entries.",
                   DESCRIBE_PROMPT.format(database=t["database"], table=t["table"], columns=columns[:3000]), "low")
    try:
        drafted = json.loads(reply[reply.find("{"): reply.rfind("}") + 1])
    except json.JSONDecodeError:
        drafted = {"description": f"Table {t['table']} from the {t['database']} database.", "grain": "one row per record"}
    card = {"table": t["table"], "description": drafted["description"], "grain": drafted["grain"],
            "freshness": "static", "traffic": "n/a", "joins": t["joins"], "lookalikes": [],
            "columns": t["columns"], "row_count": None, "date_range": None, "examples": [],
            "source": t["source"], "database": t["database"]}
    card["search_text"] = (f"Table {card['table']}. {card['description']} One row = {card['grain']}. "
                           f"Freshness: static. Traffic: n/a. Columns: {', '.join(c['name'] for c in t['columns'])}.")
    return card


def make_distractor_cards():
    pool = distractor_pool()[: max(SIZES.values())]
    DISTRACTOR_DIR.mkdir(exist_ok=True)
    todo = [t for t in pool if not (DISTRACTOR_DIR / f"{t['table']}.yaml").exists()]
    print(f"{len(pool)} distractor tables ({sum(t['source'] != 'BIRD' for t in pool)} TPC, "
          f"{sum(t['source'] == 'BIRD' for t in pool)} BIRD); drafting {len(todo)} new cards...")
    with ThreadPoolExecutor(max_workers=8) as workers:
        for card in workers.map(draft_card, todo):
            (DISTRACTOR_DIR / f"{card['table']}.yaml").write_text(yaml.safe_dump(card, sort_keys=False, allow_unicode=True))
    ORDER_FILE.write_text("\n".join(t["table"] for t in pool) + "\n")
    print(f"Saved cards to {DISTRACTOR_DIR}")


# ---------------------------------------------------------------------
# 3. Load a catalog of a given size (used by every version)
# ---------------------------------------------------------------------
def load_catalog(size=28):
    """{table: card} for our 28 tables + the first N distractors."""
    cards = {p.stem: yaml.safe_load(p.read_text()) for p in sorted(CARDS_DIR.glob("*.yaml"))}
    if SIZES[size]:
        for name in ORDER_FILE.read_text().split()[: SIZES[size]]:
            cards[name] = yaml.safe_load((DISTRACTOR_DIR / f"{name}.yaml").read_text())
    return cards


if __name__ == "__main__":
    make_distractor_cards()
    for size in SIZES:
        print(f"catalog {size}: {len(load_catalog(size))} tables")
